package bank;

public class TypeOperation {
	
	private int id;
	private String nom;
	
	 public TypeOperation(String nom) {
	        this.id = id;
	        this.nom = nom;
	    }
	 
	 // Getters
	    public int getId() {
	        return id;
	    }

	    public String getNom() {
	        return nom;
	    }
	    
	    //Setters
	    public void setId(int id) {
	        this.id = id;
	    }

	    public void setNom(String nom) {
	        this.nom = nom;
	    }

}
